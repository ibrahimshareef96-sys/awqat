"""Builds src/quran/fontHashes.ts: the SHA-256 of each of the 604 King Fahd Complex page fonts (QPC V2, 1421 print).

Usage: python3 -I scripts/make-font-hashes.py /path/to/folder-of-fonts
The folder holds p1.woff2 ... p604.woff2, downloaded once from https://static.qurancdn.com/fonts/quran/hafs/v2/woff2/.
The app checks every font it downloads against this list before keeping it, so a changed or damaged font is never used
to draw the Quran. The fonts themselves are not bundled; only their hashes are.
"""
import base64
import hashlib
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "quran" / "fontHashes.ts"
PAGES = 604


def main(folder: str) -> None:
    hashes = []
    for page in range(1, PAGES + 1):
        data = (Path(folder) / f"p{page}.woff2").read_bytes()
        assert data[:4] == b"wOF2", f"page {page}: not a WOFF2 file"
        assert 1000 < len(data) < 400_000, f"page {page}: unexpected size {len(data)}"
        hashes.append(base64.b64encode(hashlib.sha256(data).digest()).decode("ascii"))
    assert len(set(hashes)) == PAGES, "two pages share a font"
    rows = ",\n".join(f'  "{h}"' for h in hashes)
    OUT.write_text(
        "// Generated by scripts/make-font-hashes.py from the 604 QPC V2 page fonts (King Fahd Complex, 1421 print),\n"
        "// as served by Quran Foundation. Do not edit by hand.\n\n"
        "/** SHA-256 of each page's font, base64; index 0 = page 1. */\n"
        f"export const FONT_SHA256: readonly string[] = [\n{rows},\n];\n"
    )
    print(f"wrote {len(hashes)} hashes to {OUT}")


if __name__ == "__main__":
    main(sys.argv[1])
