"""Builds src/quran/data.ts from Tanzil's Quran metadata (quran-data.xml, CC BY, tanzil.net) and the 1421 print's
page map (scripts/page-starts-1421.json, from scripts/fetch-page-starts-1421.py).

Usage: python3 -I scripts/make-quran-data.py /path/to/quran-data.xml
The XML is read as data only: the surah names, their ayah counts and the ayah each juz starts at. The pages are the
King Fahd Complex 1421 print's (the one the reader draws), which ends some pages on other ayat than Tanzil's map (the
1405 print). The output is the 604 page starts, the page each juz starts on, and the surah names.
"""
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "quran" / "data.ts"
PAGE_STARTS = Path(__file__).resolve().parent / "page-starts-1421.json"


def main(xml_path: str) -> None:
    root = ET.parse(xml_path).getroot()
    suras = [(int(s.get("index")), s.get("tname"), int(s.get("ayas"))) for s in root.iter("sura")]
    arabic = [s.get("name") for s in root.iter("sura")]
    assert all(name and all("؀" <= ch <= "ۿ" or ch == " " for ch in name) for name in arabic), \
        "expected Arabic surah names"
    starts_1421 = json.loads(PAGE_STARTS.read_text())["pages"]
    pages = [(i + 1, int(s), int(a)) for i, (s, a) in enumerate(starts_1421)]
    assert all(1 <= s <= 114 and 1 <= a <= suras[s - 1][2] for _, s, a in pages), "a page starts at no such ayah"
    assert [(s, a) for _, s, a in pages] == sorted((s, a) for _, s, a in pages), "pages out of order"
    juzs = [(int(j.get("index")), int(j.get("sura")), int(j.get("aya"))) for j in root.iter("juz")]
    assert [s[0] for s in suras] == list(range(1, 115)), "expected 114 surahs in order"
    assert [p[0] for p in pages] == list(range(1, 605)), "expected 604 pages in order"
    assert [j[0] for j in juzs] == list(range(1, 31)), "expected 30 juz in order"

    def page_of(sura: int, aya: int) -> int:
        """The page on which (sura, aya) falls: the last page starting at or before it."""
        best = 1
        for index, s, a in pages:
            if (s, a) <= (sura, aya):
                best = index
        return best

    juz_pages = [page_of(s, a) for _, s, a in juzs]
    names = ",".join(f'"{name}"' for _, name, _ in suras)
    names_ar = ",".join(f'"{name}"' for name in arabic)
    ayas = ",".join(str(n) for _, _, n in suras)
    starts = ",".join(f"[{s},{a}]" for _, s, a in pages)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/make-quran-data.py from Tanzil's quran-data.xml (CC BY, https://tanzil.net) and the\n"
        "// King Fahd Complex 1421 print's page map (scripts/page-starts-1421.json, from Quran.com).\n"
        "// The Madinah mushaf: 604 pages, 30 juz, 114 surahs. Do not edit by hand.\n\n"
        "export const PAGES = 604;\n\n"
        f"/** Surah names (transliterated), index 0 = surah 1. */\nexport const SURA_NAMES: readonly string[] = [{names}];\n\n"
        f"/** Surah names in Arabic, index 0 = surah 1. */\nexport const SURA_NAMES_AR: readonly string[] = [{names_ar}];\n\n"
        f"/** Verses in each surah, index 0 = surah 1. */\nexport const SURA_AYAS: readonly number[] = [{ayas}];\n\n"
        f"/** Where each page starts, [surah, ayah]; index 0 = page 1. */\n"
        f"export const PAGE_START: readonly (readonly [number, number])[] = [{starts}];\n\n"
        f"/** The page each juz starts on; index 0 = juz 1. */\nexport const JUZ_START_PAGE: readonly number[] = "
        f"[{','.join(str(p) for p in juz_pages)}];\n"
    )


if __name__ == "__main__":
    main(sys.argv[1])
