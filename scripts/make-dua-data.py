"""Builds src/faith/duaData.ts from Hisn al-Muslim's chapters on hisnmuslim.com.

Usage: python3 -I scripts/make-dua-data.py /path/to/folder
The folder holds https://www.hisnmuslim.com/api/ar/25.json (the adhkar after the salam) and 26.json (the Istikhara),
as fetched on 30 Oct 2026, each checked by its SHA-256 below.

Only Arabic words are kept, cut from those files by the first and last words named here, so nothing is typed. Nothing
of the Quran is kept: items 70 (the three Quls) and 71 (Ayat al-Kursi) are read in the app's mushaf. The line drawn is
the adhkar's (scripts/make-adhkar-data.py): a hadith dua that echoes a Quranic phrase inside its own words is a dua.
The Quran cited after the Istikhara in the book (Al Imran 159) is left out, with the words around it.

Checked on 30 Oct 2026: every item against rn0x/hisn_almuslim_json's copy of the book, letter by letter (they differ
only in the counts written inside the words and in spelling of the hamza), and the Istikhara against Bukhari 1166 on
sunnah.com. Names, counts and sources in English are ours; the source lines were read on sunnah.com the same day.
"""
import hashlib
import json
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "faith" / "duaData.ts"
SHA256 = {
    "25.json": "4fba964763cb094a26c4adf811a12e1172e31034edc27429f6b8d75ccf004809",
    "26.json": "5bebae926f8cb03b86ea0c3f079983143237a7d1d93202ec333e74dd85f1dfc3",
}

# id: (file, the book's item, its first words, its last words, count, English name, source).
DUAS = {
    "istighfar": ("25.json", 66, "أَسْتَغْفِرُ", "وَالْإِكْرَامِ", 1, "Istighfar, then Antas-Salam", "Muslim 591"),
    "la-mani": ("25.json", 67, "لاَ إِلَهَ", "مِنْكَ الجَدُّ", 1, "None can withhold", "Bukhari 844, Muslim 593"),
    "la-hawla": ("25.json", 68, "لَا إِلَهَ", "الكَافِرُونَ", 1, "None but Allah, sincerely", "Muslim 594a"),
    "tasbih": ("25.json", 69, "سُبْحَانَ اللَّهِ", "شَيْءٍ قَدِيرٌ", 1, "Tasbih, tahmid and takbir", "Muslim 597a"),
    "ten": ("25.json", 72, "لاَ إِلَهَ", "شَيْءٍ قَدِيرٌ", 10, "None but Allah, ten times",
            "Tirmidhi 3474, Ahmad 4/227"),
    "ilman": ("25.json", 73, "اللَّهُمَّ", "مُتَقَبَّلاً", 1, "Knowledge, provision and deeds", "Ibn Majah 925, sahih (Darussalam)"),
    "istikhara": ("26.json", 74, "اللَّهُمَّ إِنِّي أَسْتَخِيرُكَ", "أَرْضِنِي بِهِ", 1, "The du'a of Istikhara", "Bukhari 1166"),
}


def cut(text: str, first: str, last: str) -> str:
    # NFC puts the vowel marks in one order, so the words named here match however the file orders them.
    whole, head, tail = (unicodedata.normalize("NFC", s) for s in (text, first, last))
    start = whole.index(head)
    return whole[start:whole.index(tail, start) + len(tail)].strip()


def main(folder: Path) -> None:
    items = {}
    for name, want in SHA256.items():
        raw = (folder / name).read_bytes()
        got = hashlib.sha256(raw).hexdigest()
        if got != want:
            sys.exit(f"{name}: SHA-256 {got} is not the file this was checked against")
        chapter = json.loads(raw.decode("utf-8-sig"))
        items[name] = {item["ID"]: item["ARABIC_TEXT"] for item in next(iter(chapter.values()))}
    rows = [{"id": key, "name": name, "text": cut(items[file][item], first, last), "count": count, "source": source}
            for key, (file, item, first, last, count, name, source) in DUAS.items()]
    body = ",\n".join("  " + json.dumps(row, ensure_ascii=False, separators=(",", ":")) for row in rows)
    OUT.write_text(
        "// Generated by scripts/make-dua-data.py from Hisn al-Muslim's chapters on hisnmuslim.com (25.json, 26.json).\n"
        "// Arabic words, cut from those files; nothing of the Quran. Do not edit by hand.\n"
        'import type { Dua } from "../modes/registry.ts";\n\n'
        f"export const DUAS: readonly Dua[] = [\n{body},\n];\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(Path(sys.argv[1]))
